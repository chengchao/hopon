const FOLLOW_UP = {
  a: (game: string) => GAMES[game].followUp,
  b: (game: string) => `${GAMES[game].followUp} Then re-render music.wav.`,
  c: (game: string) =>
    `${GAMES[game].followUp} Reply with only the new Lyria prompt.`,
};

const ffprobeSeconds = (file: string) =>
  Number(
    execFileSync("ffprobe", [
      "-v",
      "error",
      "-show_entries",
      "format=duration",
      "-of",
      "csv=p=0",
      file,
    ])
      .toString()
      .trim()
  );

// The feed's format (#114): Opus 64 kbps.
const toOpus = (input: string, output: string) => {
  execFileSync("ffmpeg", [
    "-y",
    "-loglevel",
    "error",
    "-i",
    input,
    "-c:a",
    "libopus",
    "-b:a",
    "64k",
    output,
  ]);
  return statSync(output).size;
};

// Loop body: the tail cross-faded (equal power) into the head, then the middle. Length = clip - CROSSFADE_S.
const crossfadeLoop = (input: string, output: string) => {
  const length = ffprobeSeconds(input);
  const d = CROSSFADE_S;
  execFileSync("ffmpeg", [
    "-y",
    "-loglevel",
    "error",
    "-i",
    input,
    "-filter_complex",
    `[0]atrim=0:${d},asetpts=N/SR/TB[h];[0]atrim=${d}:${length - d},asetpts=N/SR/TB[m];[0]atrim=${length - d}:${length},asetpts=N/SR/TB[t];[t][h]acrossfade=d=${d}:c1=qsin:c2=qsin[x];[x][m]concat=n=2:v=0:a=1`,
    "-c:a",
    "libopus",
    "-b:a",
    "64k",
    output,
  ]);
  return statSync(output).size;
};

const lyria = async (prompt: string, mp3: string) => {
  const started = Date.now();
  const response = await fetch(
    "https://generativelanguage.googleapis.com/v1beta/interactions",
    {
      body: JSON.stringify({ input: prompt, model: "lyria-3-clip-preview" }),
      headers: {
        "content-type": "application/json",
        "x-goog-api-key": process.env.GEMINI_API_KEY ?? "",
      },
      method: "POST",
    }
  );
  const json = (await response.json()) as {
    steps?: {
      type: string;
      content?: { type: string; data?: string; text?: string }[];
    }[];
  };
  const blocks = (json.steps ?? [])
    .filter((step) => step.type === "model_output")
    .flatMap((step) => step.content ?? []);
  const audio = blocks.find((block) => block.type === "audio")?.data;
  if (!audio) {
    throw new Error(
      `lyria ${response.status}: ${JSON.stringify(json).slice(0, 400)}`
    );
  }
  writeFileSync(mp3, Buffer.from(audio, "base64"));
  return {
    lyriaSeconds: Math.round((Date.now() - started) / 100) / 10,
    lyriaText: blocks
      .filter((block) => block.type === "text")
      .map((block) => block.text)
      .join("\n"),
  };
};

// Renders a model-written music.mjs in a fresh dir with no env, as the box would; times it.
const renderScript = (script: string) => {
  const dir = mkdtempSync(path.join(tmpdir(), "hopon-music-"));
  writeFileSync(path.join(dir, "music.mjs"), script);
  const started = Date.now();
  execFileSync(process.execPath, ["music.mjs"], {
    cwd: dir,
    env: { PATH: process.env.PATH },
    stdio: "ignore",
    timeout: 120_000,
  });
  return {
    renderMs: Date.now() - started,
    wav: path.join(dir, "music.wav"),
  };
};

const previewHtml = (gameJs: string) =>
  `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>html,body{margin:0;background:#000;overflow:hidden;touch-action:none}</style></head><body><script src="../../runtime.js"></script><script>${gameJs.replaceAll("</script", String.raw`<\/script`)}</script></body></html>`;

const runArm = async (arm: "a" | "b" | "c", game: string, modelId: string) => {
  const dir = path.join(OUT, game, `${arm}-${modelId}`);
  mkdirSync(dir, { recursive: true });
  const box = await LocalBox.create();
  const original = readFileSync(
    path.join(HERE, "games", `${game}.ts`),
    "utf-8"
  );
  await box.writeFile("game.ts", original);
  const { session } = await createMaker({ box, modelId });

  let codes: string[] = [];
  session.subscribe((event) => {
    if (
      event.type === "tool_execution_start" &&
      event.toolName === "run_node"
    ) {
      codes.push(String(event.args.code));
    }
  });
  const spent = () =>
    session.messages
      .filter(
        (message): message is AssistantMessage => message.role === "assistant"
      )
      .reduce((sum, message) => sum + message.usage.cost.total, 0);
  const lastReply = () =>
    session.messages
      .findLast(
        (message): message is AssistantMessage => message.role === "assistant"
      )
      ?.content.flatMap((part) => (part.type === "text" ? [part.text] : []))
      .join("")
      .trim() ?? "";

  const turn = async (label: "first" | "edit", prompt: string) => {
    codes = [];
    const cost0 = spent();
    const started = Date.now();
    await session.prompt(prompt);
    const row: Record<string, unknown> = {
      arm,
      game,
      label,
      model: modelId,
      modelUsd: Math.round((spent() - cost0) * 10_000) / 10_000,
      patches: codes.filter((code) => code.includes("patch(")).length,
      reply: lastReply().slice(0, 600),
      runs: codes.length,
      turnSeconds: Math.round((Date.now() - started) / 100) / 10,
      writes: codes.filter((code) =>
        /write\(\s*["'`](?:game\.ts|music\.mjs)/u.test(code)
      ).length,
    };
    const suffix = label === "edit" ? "-edit" : "";
    if (arm === "a") {
      const gameTs = Buffer.from(await box.readFile("game.ts")).toString();
      const gameJs = Buffer.from(await box.readFile("game.js")).toString();
      writeFileSync(path.join(dir, `game${suffix}.ts`), gameTs);
      writeFileSync(path.join(dir, `game${suffix}.html`), previewHtml(gameJs));
      const render = await renderZzfxm(
        gameJs,
        path.join(dir, `music${suffix}.wav`)
      );
      Object.assign(row, {
        bytesAdded: gameTs.length - original.length,
        peak: Math.round(render.peak * 100) / 100,
        renderMs: render.renderMs,
        seconds: render.seconds,
      });
    } else if (arm === "b") {
      const script = Buffer.from(await box.readFile("music.mjs")).toString();
      writeFileSync(path.join(dir, `music${suffix}.mjs`), script);
      const { renderMs, wav } = renderScript(script);
      Object.assign(row, {
        opusBytes: toOpus(wav, path.join(dir, `music${suffix}.webm`)),
        renderMs,
        scriptBytes: script.length,
        seconds: Math.round(ffprobeSeconds(wav) * 10) / 10,
      });
      execFileSync("cp", [wav, path.join(dir, `music${suffix}.wav`)]);
    } else {
      const lyriaPrompt = lastReply();
      writeFileSync(path.join(dir, `prompt${suffix}.txt`), lyriaPrompt);
      const mp3 = path.join(dir, `lyria${suffix}.mp3`);
      const generated = await lyria(lyriaPrompt, mp3);
      writeFileSync(path.join(dir, `lyria${suffix}.txt`), generated.lyriaText);
      Object.assign(row, {
        lyriaSeconds: generated.lyriaSeconds,
        lyriaUsd: LYRIA_USD,
        opusBytes: crossfadeLoop(mp3, path.join(dir, `music${suffix}.webm`)),
        promptWords: lyriaPrompt.split(/\s+/u).length,
        seconds: Math.round((ffprobeSeconds(mp3) - CROSSFADE_S) * 10) / 10,
      });
    }
    writeFileSync(
      path.join(dir, `result${suffix}.json`),
      JSON.stringify(row, null, 2)
    );
    console.log(JSON.stringify(row));
    return row;
  };

  try {
    return [
      await turn("first", PROMPTS[arm](game)),
      await turn("edit", FOLLOW_UP[arm](game)),
    ];
  } catch (error) {
    const row = { arm, error: String(error), game, model: modelId };
    console.log(JSON.stringify(row));
    return [row];
  } finally {
    session.dispose();
  }
};

if (import.meta.main) {
  const { values } = parseArgs({
    options: {
      arms: { default: "a,b,c", type: "string" },
      games: { default: Object.keys(GAMES).join(","), type: "string" },
      models: { default: "claude-haiku-5-5,claude-sonnet-5-5", type: "string" },
    },
  });
  mkdirSync(OUT, { recursive: true });
  const games = values.games.split(",");
  // One worker per arm × model; games run in order within it.
  const jobs = values.arms.split(",").flatMap((arm) =>
    (arm === "c" ? ["claude-sonnet-5-5"] : values.models.split(",")).map(
      async (model) => {
        const rows = [];
        for (const game of games) {
          // oxlint-disable-next-line no-await-in-loop -- one run at a time per worker
          rows.push(...(await runArm(arm as "a" | "b" | "c", game, model)));
        }
        return rows;
      }
    )
  );
  const perJob = await Promise.all(jobs);
  const rows = perJob.flat();
  writeFileSync(
    path.join(OUT, `results-${Date.now()}.json`),
    JSON.stringify(rows, null, 2)
  );
}
