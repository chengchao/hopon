// PROTOTYPE (#129, throwaway): where does a game's music come from? Runs the three arms on five spike games as a
// follow-up Maker turn on a finished game, then the follow-up edit, and records cost, time and size.
//   A: the model writes a ZzFXM song into game.ts (skills/zzfxm-music.md); the runtime plays it.
//   B: the model writes a dependency-free Node synthesizer (music.mjs) that renders music.wav.
//   C: the model writes a Lyria 3 Clip prompt; we generate the clip and loop it with an ffmpeg cross-fade.
// node --env-file=.env music/run.ts --arms a,b,c --models claude-haiku-5-5,claude-sonnet-5-5 [--games moon-cat,...]
